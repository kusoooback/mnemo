const dicts: Record<'fr' | 'en', Record<string, string>> = { fr: { ...(fr as Dict), ...fr2 }, en: { ...en, ...en2 } }


export function useT(): (key: Key, vars?: Record<string, string | number>) => string {
  const lang = useStore((s) => s.settings.language)
  return (key, vars) => shortcut(translate(lang, key, vars))
}

export function translate(
  lang: 'fr' | 'en',
  key: Key,
  vars?: Record<string, string | number>
): string {
  let s = dicts[lang][key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
    if (typeof vars.n === 'number') {
      const plural = lang === 'fr' ? vars.n >= 2 : vars.n !== 1
      s = s.replace(/\(s\)/g, plural ? 's' : '')
    }
  }
  return s.replace(/\(s\)/g, '')
}
